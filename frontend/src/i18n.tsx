interface I18n {
  t: (key: string) => string;
}

const I18nContext = createContext<I18n | null>(null);

/** 中文翻译实现：<html lang> 固定 zh-CN，t 查词典、缺失返回 key。 */
function useZhI18n(): I18n {
  useEffect(() => {
    document.documentElement.lang = "zh-CN";
  }, []);

  const t = (key: string): string => translations[key] ?? key;
  return { t };
}

/** 应用根部的词典 Provider（main.tsx）：保留挂载结构，语言固定中文。 */
export function I18nProvider({ children }: { children: ReactNode }) {
  return <I18nContext.Provider value={useZhI18n()}>{children}</I18nContext.Provider>;
}

export function useTranslation(): I18n {
  const shared = useContext(I18nContext);
  if (shared) return shared;

  // 无 Provider 的退路（组件单测裸渲染）：与共享路径同一实现。
  return useZhI18n();
}
